def image(f,perm):return mask(perm[v]for v in vertices(f))


def automorphisms(n,faces):
    fs=set(faces)
    es={mask(t)for f in fs for t in combinations(vertices(f),2)}
    adjacency=[{v for v in range(n)if v!=u and((1<<u)|(1<<v))in es}for u in range(n)]
    deg=[len(z)for z in adjacency]
    result=[];nodes=0
    def extend(mapping,used):
        nonlocal nodes
        nodes+=1
        if len(mapping)==n:
            perm=tuple(mapping[i]for i in range(n))
            assert {image(f,perm)for f in fs}==fs
            result.append(perm);return
        candidates={}
        for u in range(n):
            if u in mapping:continue
            options=[]
            for v in range(n):
                if v in used or deg[v]!=deg[u]:continue
                if any((w in adjacency[u])!=(z in adjacency[v])for w,z in mapping.items()):continue
                if any((mask((u,w,t))in fs)!=(mask((v,mapping[w],mapping[t]))in fs)
                       for w,t in combinations(mapping,2)):continue
                options.append(v)
            candidates[u]=options
        u=min(candidates,key=lambda w:(len(candidates[w]),-sum(v in mapping for v in adjacency[w]),w))
        for v in candidates[u]:
            mapping[u]=v;extend(mapping,used|{v});del mapping[u]
    extend({},set())
    assert len(result)==len(set(result))and tuple(range(n))in result
    return sorted(result),nodes


def root_records():
    mixed,plus,private,ordinary,paths=source_filter()
    roots=[]
    for n,index in private:
        source=read(P/f'sphere-triangulations-{n:02d}.json')['classes'][index]
        assert source['index']==index
        faces=source['face_masks'];edges,degrees=sphere_check(faces,n);flag_check(faces,edges,n)
        assert degrees.count(6)==1 and set(degrees)<={4,5,6}
        roots.append(dict(order=n,index=index,face_masks=faces,degree_vector=degrees,
                          negative_vertex=degrees.index(6)))
    assert [(r['order'],r['index'])for r in roots]==[(9,22),(10,185),(11,762)]
    return roots,paths,ordinary,plus


def cover_check(cover,expected_link):
    assert cover['link']==expected_link
    n=expected_link['order'];root_faces={f<<1 for f in expected_link['face_masks']}
    first=1|(1<<(expected_link['negative_vertex']+1))
    assert cover['first_exception']==first
    local,nodes=automorphisms(n,expected_link['face_masks'])
    full=[]
    for aut in local:
        for outside in permutations(range(n+1,13)):
            perm=(0,)+tuple(v+1 for v in aut)+outside
            assert sorted(perm)==list(range(13))and image(first,perm)==first
            assert {image(f,perm)for f in root_faces}==root_faces
            full.append(perm)
    assert len(full)==len(set(full))==len(local)*factorial(12-n)==cover['group_order']
    group=set(full)
    assert all(tuple(a[b[v]]for v in range(13))in group for a in group for b in group)
    pairs=[mask(t)for t in combinations([v for v in range(13)if not first>>v&1],2)]
    assert len(pairs)==55 and [r['pair']for r in cover['coverage']]==pairs
    discoveries={};orbits={}
    for pair,record in zip(pairs,cover['coverage']):
        orbit={image(pair,p)for p in full};best=min(orbit)
        witness=min(p for p in full if image(pair,p)==best)
        if best not in discoveries:discoveries[best]=len(discoveries)
        expected=dict(pair=pair,representative_pair=best,class_index=discoveries[best],permutation=list(witness))
        assert record==expected
        assert pair&first==0 and best&first==0
        orbits.setdefault(best,set()).update(orbit)
    assert cover['second_pairs']==sorted(orbits)
    assert set.union(*orbits.values())==set(pairs)
    assert sum(map(len,orbits.values()))==55
    for best,orbit in orbits.items():
        assert min(orbit)==best and all({image(pair,p)for p in full}==orbit for pair in orbit)
    return dict(order=n,index=expected_link['index'],literal_pairs=55,
                link_automorphisms=len(local),full_group_order=len(full),
                backtracking_nodes=nodes,marked_orbits=len(orbits),
                orbit_sizes={str(k):len(v)for k,v in sorted(orbits.items())},
                discovery_label_to_pair={str(i):p for p,i in discoveries.items()},
                sorted_representative_pairs=sorted(orbits))


def main():
    start=time.monotonic()
    helper=A/'verify_two_mixed_cubic.py';accepted=read(A/'two-mixed-cubic-independent-verification.json')
    assert next(r['sha256']for r in accepted['dependencies']if r['path']==str(helper))==digest(helper)
    roots,catalogs,ordinary,plus=root_records()
    path=P/'disjoint-cubic-root-link-cover.json';data=read(path);check_bindings(data['sources'])
    assert data['status']=='COMPLETE_CANDIDATE_MARKED_ROOT_COVER'
    assert len(data['covers'])==3 and[c['link']for c in data['covers']]==roots
    result=[cover_check(c,r)for c,r in zip(data['covers'],roots)]
    assert [r['marked_orbits']for r in result]==[14,13,20]
    assert [r['link_automorphisms']for r in result]==[4,6,4]
    assert [r['full_group_order']for r in result]==[24,12,4]
    assert sum(r['literal_pairs']for r in result)==165
    cases=[]
    for root_index,c in enumerate(data['covers']):
        for second in c['second_pairs']:
            for sign in(-2,1):
                first=c['first_exception'];assert first&second==0
                negative=vertices(first|second)if sign==-2 else vertices(first)
                positive=()if sign==-2 else vertices(second)
                ordinary_vertices=sorted(set(range(13))-set(negative)-set(positive))
                assert len(ordinary_vertices)==9  # All thirteen include four exceptional endpoints.
                # In a disconnected ordinary vertex link, its center is removed:
                # eight good vertices plus the four exceptional endpoints remain.
                cross_min=8*2+len(negative)*3+len(positive)
                assert cross_min==(28 if sign==-2 else 24)and cross_min>18
                cases.append(dict(case_index=len(cases),root_index=root_index,second_pair=second,
                                  second_value=sign,negative_endpoints=list(negative),positive_endpoints=list(positive),
                                  allowed_constants=[1,2],negative_endpoint_orders=[9,11],
                                  positive_endpoint_orders=[7,10],
                                  flag_vertices=sorted(set(ordinary_vertices)|set(negative))))
    assert len(cases)==94 and len({(c['root_index'],c['second_pair'],c['second_value'])for c in cases})==94
    first=data['covers'][0];controls={}
    bad=deepcopy(first);bad['coverage'].pop()
    controls['missing_literal_pair']=rejected(lambda:cover_check(bad,roots[0]))
    bad=deepcopy(first);bad['coverage'][1]=deepcopy(bad['coverage'][0])
    controls['duplicate_literal_pair']=rejected(lambda:cover_check(bad,roots[0]))
    bad=deepcopy(first);bad['coverage'][0]['permutation'][0]=1
    controls['nonbijective_witness']=rejected(lambda:cover_check(bad,roots[0]))
    bad=deepcopy(first);bad['coverage'][0]['representative_pair']=first['second_pairs'][-1]
    controls['wrong_orbit_target']=rejected(lambda:cover_check(bad,roots[0]))
    bad=deepcopy(first);bad['second_pairs'].pop()
    controls['missing_orbit']=rejected(lambda:cover_check(bad,roots[0]))
    bad=deepcopy(first);bad['link']['index']+=1
    controls['wrong_root_id']=rejected(lambda:cover_check(bad,roots[0]))
    tetra_aut,small_nodes=automorphisms(4,[7,11,13,14]);assert len(tetra_aut)==24
    controls['tetrahedral_boundary_automorphisms']=24
    dependencies={Path(r['path'])for r in data['sources']}
    dependencies.update(catalogs+[Path(__file__),path,helper,A/'verify_two_adjacent_negative_cubic.py',
        A/'two-mixed-cubic-independent-verification.json',A/'two-mixed-cubic-audit.md',
        A/'two-adjacent-negative-cubic-independent-verification.json',
        A/'d10-normalization-spheres-independent-verification.json',
        R/'one-negative-quadratic-derivative.md',S/'one-negative-quadratic-derivative-independent-audit.md'])
    report=dict(status='VERIFIED_COMPLETE_DISJOINT_CUBIC_ORDINARY_ROOT_LINK_COVER',
                global_goal='OPEN',coverage_scope='Ordinary quadratic coefficients0/1, c1/2, binary quartics, two disjoint exceptional Fourier pairs with at least one -2 and other -2/+1.',
                root_covers=result,total_literal_pairs=165,total_marked_types=47,total_signed_cases=94,
                cases=cases,probe_outcomes_not_audited=True,no_derivative_exclusion_claimed=True,
                authoritative_case_key=['root_index','second_pair','second_value'],
                discovery_label_warning='coverage.class_index is the first-encounter label, not an index into sorted second_pairs; every label-to-mask relation is recorded and checked.',
                ordinary_flag_sphere_classes=ordinary,positive_endpoint_sphere_classes=plus,
                positive_endpoint_flag_assumption=False,symmetry_of_original_function_assumed=False,
                controls=controls,producer_imports=False,research_solver_used=False,
                seconds=time.monotonic()-start,
                dependencies=[bound(p)for p in sorted(dependencies)])
    (A/'disjoint-cubic-root-link-cover-independent-verification.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps(report,indent=2))


